import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'
import {harness} from './harness.mjs'
import {attestArrival} from './readiness-helpers.mjs'
const photo=(await readFile('tests/fixtures/checklist.png')).toString('base64')
const now='2026-10-26T14:00:00Z',start='2026-10-26',end='2026-10-29'
const calendar='BEGIN:VCALENDAR\r\nVERSION:2.0\r\nBEGIN:VEVENT\r\nUID:synthetic-cabin-1\r\nDTSTART;VALUE=DATE:20261026\r\nDTEND;VALUE=DATE:20261028\r\nSUMMARY:Channel collision\r\nEND:VEVENT\r\nEND:VCALENDAR\r\n'
export async function alternativeRecoveryJourney({screens=async()=>{},act,guestAct}={}){
 const h=await harness({now})
 try{
  const command=(name,input,cookie=h.owner,status=200)=>act&&cookie===h.owner&&status===200&&name.startsWith('recovery.')?act(h,name,input):h.cmd(name,input,cookie,status)
  const home=await h.cmd('property.save',{name:'Cedar Creek Cabin',ownerName:'Morgan Carter',ownerEmail:'morgan@stay.example',commissionBps:2000})
  const destination=await h.cmd('property.save',{name:'Lake House',ownerName:'Jordan Davis',ownerEmail:'jordan@stay.example',commissionBps:1500})
  const original=await h.person('Luis'),backup=await h.person('Ana'),outsider=await h.person('Taylor')
  for(const p of [home,destination]){
   await h.cmd('ledger.configure',{propertyId:p.id,legalEntity:p.name+' LLC'})
   await h.cmd('home.settings',{propertyId:p.id,address:p===home?'12 Cedar Lane, Asheville, NC':'18 Lake Road, Asheville, NC',timeZone:'America/New_York',checkInTime:'16:00',checkOutTime:'10:00',cleanerId:original.id,checklist:['Kitchen clean','Beds made'],photosRequired:1})
   await h.cmd('recovery.settings',{propertyId:p.id,cleanerIds:[original.id,backup.id],auto:false,creditLimitCents:10000,cleaningLimitCents:5000})
  }
  await h.cmd('reservation.request',{propertyId:home.id,channel:'direct',guestName:'Departing guest',start:'2026-10-24',end:start})
  const request=await h.cmd('reservation.request',{propertyId:home.id,channel:'direct',guestName:'Megan Ortiz',guestEmail:'megan@stay.example',start,end})
  const initial=await h.accessState(),oldCode=initial.codes.find(c=>c.bookingId===request.bookingId&&c.holder==='guest')
  const draft=await h.cmd('calendar.prepare',{propertyId:home.id,channel:'airbnb',calendar})
  await h.cmd('calendar.approve',{id:draft.id,revision:draft.revision})
  let state=await h.accessState(),row=state.recoveries.find(r=>r.bookingId===request.bookingId&&!r.issue)
  assert.equal(row.trigger,'reservation_conflict','Actual confirmed channel inventory opens a durable recovery')
  assert.equal(state.recoveries.filter(r=>r.bookingId===request.bookingId&&!r.issue).length,1)
  await h.restart()
  row=(await h.accessState()).recoveries.find(r=>r.id===row.id)
  const proposal=()=>({id:row.id,revision:row.revision,cleanerId:backup.id,creditCents:7500,extraCleaningCents:2500,alternativePropertyId:destination.id,alternativeStart:start,alternativeEnd:end,why:'Approved available alternative after a late channel collision; owner covers the credit and extra preparation'})
  row=await command('recovery.propose',proposal())
  await screens(h,'proposed',row)
  await h.cmd('recovery.approve',{id:row.id,revision:row.revision},outsider.cookie,403)
  const competitor=await h.cmd('reservation.request',{propertyId:destination.id,channel:'direct',guestName:'Newly held destination',start,end})
  await h.cmd('recovery.approve',{id:row.id,revision:row.revision},h.owner,409)
  const competing=(await h.state()).bookings.find(b=>b.id===competitor.bookingId)
  await h.cmd('reservation.cancel',{id:competing.id,revision:competing.revision})
  row=await command('recovery.propose',proposal())
  row=await command('recovery.reject',{id:row.id,revision:row.revision})
  assert.equal((await h.state()).bookings.find(b=>b.id===request.bookingId).propertyId,home.id,'Denied alternative changes neither inventory nor balances')
  row=await command('recovery.propose',proposal())
  await command('recovery.approve',{id:row.id,revision:row.revision})
  state=await h.accessState();row=state.recoveries.find(r=>r.id===row.id)
  const booking=state.bookings.find(b=>b.id===request.bookingId),code=state.codes.find(c=>c.id===row.codeId),job=state.turnovers.find(t=>t.id===row.turnoverId)
  assert.equal(booking.propertyId,destination.id)
  assert.equal(job.purpose,'arrival');assert.equal(job.nextBookingId,booking.id)
  assert.equal(code.propertyId,destination.id);assert.notEqual(code.code,oldCode.code);assert.equal(code.link,oldCode.link)
  assert.equal(state.codes.find(c=>c.id===oldCode.id).status,'revoked')
  assert.equal(state.statements.find(s=>s.id===row.statementId).propertyId,home.id,'The original owner bears the exact approved recovery spend')
  assert.equal(state.statements.find(s=>s.id===row.statementId).netCents,-10000)
  assert.ok(!state.ledger.journals.filter(j=>j.sourceId===row.statementId).flatMap(j=>j.lines).some(l=>l.account==='cash'),'Relocation never fabricates a transfer')
  await h.cmd('recovery.undo',{id:row.id,revision:row.revision,reason:'A move must not silently restore another owner and home'},h.owner,409)
  await h.restart();row=(await h.accessState()).recoveries.find(r=>r.id===row.id)
  await screens(h,'active',row)
  const privateState=await h.state(backup.cookie);assert.equal(privateState.recoveries.find(r=>r.id===row.id).alternativeOrigin,undefined)
  row=await h.cmd('recovery.accept',{id:row.id,revision:row.revision},backup.cookie)
  const currentJob=(await h.state()).turnovers.find(t=>t.id===row.turnoverId)
  await h.cmd('turnover.complete',{id:currentJob.id,revision:currentJob.revision,checks:currentJob.checklist,caption:'Lake House prepared for Megan',photos:[{photo,mimeType:'image/png'}]},backup.cookie)
  row=(await h.accessState()).recoveries.find(r=>r.id===row.id)
  row=await command('recovery.access',{id:row.id,revision:row.revision})
  await attestArrival(h,request.bookingId)
  await h.cmd('recovery.close',{id:row.id,revision:row.revision},h.owner,409)
  const guest=await h.verifyGuest(code.link)
  let response=await (guestAct??((h,path,input,cookie)=>h.send(path,input,cookie)))(h,'/stay/'+code.link,{action:'settlement',caseId:row.id,revision:row.revision,response:'accept'},guest);assert.equal(response.status,303,response.text)
  row=(await h.accessState()).recoveries.find(r=>r.id===row.id)
  await command('recovery.close',{id:row.id,revision:row.revision})
  row=(await h.accessState()).recoveries.find(r=>r.id===row.id);assert.equal(row.status,'ready')
  await screens(h,'ready',row)
  response=await (guestAct??((h,path,input,cookie)=>h.send(path,input,cookie)))(h,'/stay/'+code.link,{action:'recovery-confirm',caseId:row.id,revision:row.revision,response:'confirmed'},guest);assert.equal(response.status,303,response.text)
  row=(await h.accessState()).recoveries.find(r=>r.id===row.id)
  row=await command('recovery.recurrence',{id:row.id,revision:row.revision,reference:'synthetic-cabin-2',note:'Guest confirmed working access and inspector rechecked the completed preparation and original owner adjustment',confirm:'yes'})
  state=await h.accessState();row=state.recoveries.find(r=>r.id===row.id);assert.equal(row.status,'closed')
  assert.equal(state.statements.filter(s=>s.recoveryId===row.id).reduce((n,s)=>n+s.netCents,0),-10000)
  await screens(h,'closed',row)
  const channelCase=state.recoveries.find(r=>r.trigger==='reservation_conflict'&&r.bookingId!==request.bookingId)
  const channelBooking=state.bookings.find(b=>b.id===channelCase.bookingId)
  assert.equal(channelBooking.channel,'airbnb');assert.equal(channelBooking.propertyId,home.id)
  // External reservations require their real source acceptance; a local correction cannot pretend to move one.
  const external=await h.cmd('recovery.propose',{id:channelCase.id,revision:channelCase.revision,cleanerId:backup.id,creditCents:0,extraCleaningCents:0,alternativePropertyId:destination.id,alternativeStart:'2026-11-01',alternativeEnd:'2026-11-03',why:'Review source-authorized alternative with the host'})
  assert.ok(external.proposal.alternative.blockedReason)
  await h.cmd('recovery.approve',{id:external.id,revision:external.revision})
  const final=await h.state();assert.equal(final.bookings.find(b=>b.id===channelBooking.id).propertyId,home.id)
  assert.equal(final.recoveries.find(r=>r.id===external.id).status,'escalated')
 }finally{await h.close()}
}
