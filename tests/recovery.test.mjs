import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { harness } from './harness.mjs'

// The stays are set on the home's own clock: the previous guests leave at midnight today and Ana arrives two hours
// from now (still ahead if a daylight-saving change makes that wall time ambiguous), so at any time of day the
// turnover can be finished and her check-in message is already due.
const zone = 'America/New_York'
const local = ms => { const p = Object.fromEntries(new Intl.DateTimeFormat('en-CA', { timeZone: zone, year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' }).formatToParts(ms).map(x => [x.type, x.value])); return { date: `${p.year}-${p.month}-${p.day}`, time: `${p.hour}:${p.minute}` } }
const plus = (date, n) => new Date(Date.parse(`${date}T00:00:00Z`) + n * 86_400_000).toISOString().slice(0, 10)
const photo = (await readFile('tests/fixtures/checklist.png')).toString('base64')

test('cancelled cleaner recovery binds approval, rebooks, rotates only changed messages, credits, verifies photos and posts a reversible owner balance', async () => {
 const h = await harness()
 try {
  assert.equal((await h.send('/app/recovery/setup', undefined, h.owner)).status, 200)
  await h.cmd('recovery.ai.test', {}, h.owner, 409)
  const home = await h.cmd('property.save', { name: 'Fernwood Cabin', ownerName: 'Morgan Lee', ownerEmail: 'morgan@stay.example', commissionBps: 2000 })
  const original = await h.person('Taylor'), replacement = await h.person('Casey'), outsider = await h.person('Dale')
  const manager = await h.person('Riley', 'manager')
  const today = local(Date.now()).date, arrival = local(Date.now() + 7_200_000)
  await h.cmd('home.settings', { propertyId: home.id, address: '18 Fernwood Lane, Boone, NC', timeZone: zone, checkInTime: arrival.time, checkOutTime: '00:00', cleanerId: original.id, checklist: ['Beds made', 'Kitchen clean'], photosRequired: 1 })
  let policy = await h.cmd('recovery.settings', { propertyId: home.id, cleanerIds: [original.id, replacement.id], auto: false, creditLimitCents: 10_000, cleaningLimitCents: 5000 })
  const prior = await h.cmd('reservation.request', { propertyId: home.id, channel: 'direct', kind: 'stay', guestName: 'Jo', start: plus(today, -1), end: today })
  const stay = await h.cmd('reservation.request', { propertyId: home.id, channel: 'direct', kind: 'stay', guestName: 'Ana Ruiz', guestEmail: 'ana@stay.example', start: arrival.date, end: plus(arrival.date, 3) })
  let s = await h.state(), turnover = s.turnovers.find(t => t.bookingId === prior.bookingId)
  const oldCode = s.codes.find(c => c.bookingId === stay.bookingId && c.holder === 'guest' && c.status === 'issued')
  let recovery = await h.cmd('recovery.open', { turnoverId: turnover.id, trigger: 'cleaner_cancelled', reason: 'Vehicle broke down before the arrival clean' }, original.cookie)
  assert.equal(recovery.bookingId, stay.bookingId)
  const propose = (creditCents = 7500) => h.cmd('recovery.propose', { id: recovery.id, revision: recovery.revision, cleanerId: replacement.id, creditCents, extraCleaningCents: 2500, why: 'Casey can finish before check-in; compensate the delay' })
  recovery = await h.cmd('recovery.plan', { id: recovery.id, revision: recovery.revision })
  assert.equal(recovery.proposal.cleanerId, replacement.id)
  assert.equal(recovery.status, 'proposed')
  assert.equal((await h.state()).statements.length, 0)
  await h.cmd('recovery.approve', { id: recovery.id, revision: recovery.revision }, replacement.cookie, 403)
  // Recipients are part of the approval, even if booking.details keeps its revision.
  await h.cmd('booking.details', { id: stay.bookingId, guestName: 'Ana Ruiz', guestEmail: 'ana-new@stay.example' })
  await h.cmd('recovery.approve', { id: recovery.id, revision: recovery.revision }, h.owner, 409)
  recovery = await propose(15_000)
  await h.cmd('recovery.approve', { id: recovery.id, revision: recovery.revision }, manager.cookie, 403)
  recovery = await h.cmd('recovery.reject', { id: recovery.id, revision: recovery.revision })
  policy = await h.cmd('recovery.settings', { ...policy, auto: true })
  recovery = await propose()
  assert.equal(recovery.status, 'active')
  s = await h.state(); turnover = s.turnovers.find(t => t.id === turnover.id)
  assert.equal(turnover.cleanerId, replacement.id)
  const code = s.codes.find(c => c.id === recovery.codeId)
  assert.notEqual(code.code, oldCode.code)
  assert.equal(code.link, oldCode.link)
  assert.equal(s.codes.find(c => c.id === oldCode.id).status, 'revoked')
  assert.equal(recovery.balanceCents, -10_000)
  const statement = s.statements.find(r => r.id === recovery.statementId)
  assert.equal(statement.netCents, -10_000)
  assert.deepEqual(statement.lines.map(l => l.amountCents), [-7500, -2500])
  const emails = (await h.db.prepare('SELECT message FROM rer_mail_development_outbox ORDER BY sequence').all()).results.map(r => JSON.parse(r.message))
  assert.ok(emails.some(m => m.to.includes(replacement.email) && m.text.includes('18 Fernwood Lane')))
  assert.ok(s.messages.some(m => m.id === recovery.creditMessageId && m.text.includes('$75.00')))
  const changed = s.scheduled.filter(r => r.updated)
  assert.deepEqual(changed.map(r => r.rule), ['checkin'])
  const privateState = await h.state(replacement.cookie)
  assert.ok(!privateState.codes.some(c => c.holder === 'guest'))
  assert.ok(!privateState.recoveries[0].previous)
  await h.cmd('recovery.accept', { id: recovery.id, revision: recovery.revision }, outsider.cookie, 403)
  await h.cmd('recovery.close', { id: recovery.id, revision: recovery.revision }, h.owner, 409)
  recovery = await h.cmd('recovery.accept', { id: recovery.id, revision: recovery.revision }, replacement.cookie)
  await h.cmd('turnover.complete', { id: turnover.id, revision: turnover.revision, checks: turnover.checklist, caption: 'All rooms ready for Ana', photos: [] }, replacement.cookie, 400)
  await h.cmd('turnover.complete', { id: turnover.id, revision: turnover.revision, checks: turnover.checklist, caption: 'All rooms ready for Ana', photos: [{ photo, mimeType: 'image/png' }] }, replacement.cookie)
  recovery = (await h.state()).recoveries.find(r => r.id === recovery.id)
  await h.cmd('recovery.close', { id: recovery.id, revision: recovery.revision }, h.owner, 409)
  recovery = await h.cmd('recovery.access', { id: recovery.id, revision: recovery.revision })
  await h.cmd('recovery.close', { id: recovery.id, revision: recovery.revision })
  s = await h.state(); recovery = s.recoveries.find(r => r.id === recovery.id)
  assert.equal(recovery.status, 'closed')
  assert.equal(s.messages.find(m => m.id === recovery.confirmationMessageId).status, 'sent')
  assert.equal(s.statements.filter(r => r.recoveryId === recovery.id).length, 1)
  const csv = await h.send(`/api/cabin/statements/${statement.id}.csv`, undefined, h.owner)
  assert.equal(csv.status, 200); assert.ok(csv.text.includes('($75.00)'))
  recovery = await h.cmd('recovery.undo', { id: recovery.id, revision: recovery.revision, reason: 'Owner chose to cover this from the agency balance' })
  s = await h.state(); assert.equal(recovery.status, 'undone')
  assert.equal(s.statements.filter(r => r.recoveryId === recovery.id).reduce((n, r) => n + r.netCents, 0), 0)
  assert.ok(s.turnovers.find(t => t.id === turnover.id).completion, 'Undo preserves real completed work and photo evidence')
  await h.cmd('recovery.undo', { id: recovery.id, revision: recovery.revision, reason: 'Duplicate' }, h.owner, 409)
  assert.equal((await h.send('/app/recovery/setup', undefined, h.owner)).status, 200)
  const guestReport = await h.mf.dispatchFetch(h.origin + '/stay/' + oldCode.link, { method: 'POST', headers: { origin: h.origin, 'content-type': 'application/x-www-form-urlencoded' }, body: 'reason=The+door+still+needs+attention' })
  assert.equal(guestReport.status, 200)
  assert.ok((await h.state()).recoveries.some(r => r.trigger === 'guest_problem' && r.status === 'open'))
 } finally { await h.close() }
})
