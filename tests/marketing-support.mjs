import assert from 'node:assert/strict'
export const marketingContact=n=>['synthetic-cabin-'+n,'example.invalid'].join('@')
export async function marketingOrigin(h,propertyId,n=1,input={}) {
 const stay=await h.cmd('reservation.request',{propertyId,channel:'airbnb',start:'2026-09-01',end:'2026-09-04',guestName:'Synthetic guest '+n,guestEmail:marketingContact(n),...input})
 return (await h.state()).guests.find(g=>g.bookingId===stay.bookingId)
}
export async function marketingConsent(h,id,allowed='yes',propertyId,cookie=h.owner,status=200) {
 const state=await h.state(),g=state.guests.find(g=>g.id===id),home=propertyId??state.bookings.find(b=>b.id===g.bookingId).propertyId
 return h.cmd('guest.consent',{id:g.id,revision:g.revision,propertyId:home,purpose:'marketing',identityId:g.identities.find(i=>i.kind==='email'&&i.value===state.bookings.find(b=>b.id===g.bookingId).guestEmail)?.id,allowed,source:'Guest separately requested repeat-stay marketing for this home in a reviewed written record.',confirm:'yes'},cookie,status)
}
export async function verifyMarketing(h,id) {
 const g=(await h.state()).guests.find(g=>g.id===id)
 return h.cmd('guest.identity.verify',{id,revision:g.revision,identityId:g.identities.find(i=>i.kind==='email').id,source:'Guest confirmed current contact ownership in person.',confirm:'yes'})
}
export const prepareMarketing=(h,propertyId,label='Synthetic segment')=>h.cmd('guest.marketing.prepare',{propertyId,label})
export async function marketingJourney(h) {
 const home=await h.cmd('property.save',{name:'Synthetic marketing home',ownerName:'Synthetic host',ownerEmail:marketingContact('host'),commissionBps:1500})
 const other=await h.cmd('property.save',{name:'Synthetic other home',ownerName:'Synthetic host',ownerEmail:marketingContact('other'),commissionBps:1500})
 const a=await marketingOrigin(h,home.id),b=await marketingOrigin(h,home.id,2,{channel:'vrbo',start:'2026-09-10',end:'2026-09-13'})
 const departing=await marketingOrigin(h,home.id,4,{start:'2026-11-01',end:'2026-11-04'})
 await verifyMarketing(h,departing.id);await marketingConsent(h,departing.id)
 const rejected=()=>h.cmd('guest.marketing.prepare',{propertyId:home.id,label:'Refused'},h.owner,409)
 const before=(await h.state()).guestSegments.length
 await rejected()
 await marketingConsent(h,a.id,'yes',undefined,h.owner,409)
 await verifyMarketing(h,a.id)
 const g=(await h.state()).guests.find(g=>g.id===a.id)
 await h.cmd('guest.consent',{id:g.id,revision:g.revision,propertyId:home.id,purpose:'offers',allowed:'yes',source:'Returning-offer consent only.'})
 await rejected();assert.equal((await h.state()).guestSegments.length,before,'Booking and offers consent never imply marketing consent')
 await marketingConsent(h,a.id,'yes',other.id,h.owner,409)
 await marketingConsent(h,a.id)
 const first=await prepareMarketing(h,home.id)
 let segment=(await h.state()).guestSegments.find(s=>s.id===first.id)
 assert.equal(segment.status,'prepared');assert.equal(segment.members.length,1);assert.equal(segment.members[0].email,marketingContact(1));assert.equal(segment.excluded,2,'A stay before its property-local checkout remains excluded')
 const review=s=>h.cmd('guest.marketing.review',{id:s.id,revision:s.revision})
 assert.equal((await review(first)).externalEffects,0)
 await h.cmd('guest.marketing.prepare',{propertyId:other.id,label:'Wrong home'},h.owner,409)
 await marketingConsent(h,b.id,'no')
 let state=await h.state(),ga=state.guests.find(g=>g.id===a.id),gb=state.guests.find(g=>g.id===b.id)
 const merge=await h.cmd('guest.merge',{id:gb.id,revision:gb.revision,intoId:ga.id,intoRevision:ga.revision,reason:'Reviewed source reservation references with the guest.',confirm:'yes'})
 await h.cmd('guest.marketing.review',{id:first.id,revision:first.revision},h.owner,409)
 await rejected()
 state=await h.state();assert.equal(state.guestSegments.find(s=>s.id===first.id).members.length,0,'Stale segment hides its contacts')
 const m=state.guestMerges.find(m=>m.id===merge.id);await h.cmd('guest.merge.undo',{id:m.id,revision:m.revision,confirm:'yes'})
 const fresh=await prepareMarketing(h,home.id)
 await marketingConsent(h,a.id,'no');await h.cmd('guest.marketing.review',{id:fresh.id,revision:fresh.revision},h.owner,409);await rejected()
 await marketingConsent(h,a.id)
 const contactBound=await prepareMarketing(h,home.id)
 state=await h.state();const booking=state.bookings.find(b=>b.id===a.bookingId)
 await h.cmd('booking.details',{id:booking.id,revision:booking.revision,guestName:booking.guestName,guestEmail:marketingContact(3)})
 await h.cmd('guest.marketing.review',{id:contactBound.id,revision:contactBound.revision},h.owner,409)
 await rejected()
 const current=(await h.state()).guests.find(g=>g.id===a.id),email=current.identities.find(i=>i.value===marketingContact(3))
 await h.cmd('guest.identity.verify',{id:current.id,revision:current.revision,identityId:email.id,source:'Guest confirmed the new contact.',confirm:'yes'})
 await rejected();await marketingConsent(h,a.id)
 const manager=await h.person('SyntheticManager','manager'),active=await prepareMarketing(h,home.id)
 const page=await h.send('/app/guests',undefined,h.owner);assert.match(page.text,/Repeat-stay marketing preparation/);assert.ok(page.text.includes(marketingContact(3)))
 assert.deepEqual((await h.state(manager.cookie)).guestSegments,[])
 assert.ok((await h.state(manager.cookie)).guests.every(g=>g.consents.every(c=>c.purpose!=='marketing')))
 await h.cmd('guest.marketing.prepare',{propertyId:home.id,label:'Unauthorized'},manager.cookie,403)
 await h.cmd('guest.marketing.review',{id:active.id,revision:active.revision},manager.cookie,403)
 await marketingConsent(h,a.id,'no',home.id,manager.cookie,403)
 state=await h.state();const member=state.members.find(m=>m.id===manager.id)
 await h.cmd('member.save',{...member,active:false})
 await h.cmd('guest.marketing.review',{id:active.id,revision:active.revision},h.owner,409)
 const final=await prepareMarketing(h,home.id,'Retained local preview')
 await h.restart();assert.equal((await review(final)).count,1,'Prepared local segment survives restart with unchanged authority')
 state=await h.state();assert.equal(state.guestSegments.find(s=>s.id===final.id).members[0].email,marketingContact(3))
 assert.ok(state.events.some(e=>e.action==='guest.marketing.prepare'));assert.equal(state.messages.filter(m=>m.source==='host'&&m.text.includes('marketing')).length,0)
 return {home,origin:a,segment:final}
}
